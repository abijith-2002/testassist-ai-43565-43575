@app.get(
    "/answers",
    tags=["chat"],
    summary="List all Q&A pairs from answers.txt",
    description="Returns all Q&A pairs found in the answers.txt file as reference only.",
)
def list_qa_pairs():
    """
    Returns the full contents of answers.txt file as Q&A pairs, for frontend display/reference
    (not for answer matching).
    """
    pairs = []
    try:
        with open(ANSWERS_FILE, "r", encoding="utf-8") as f:
            lines = [l.strip() for l in f if l.strip()]
        q = a = None
        for line in lines:
            if line.startswith("Q:"):
                if q and a:
                    pairs.append({"question": q, "answer": a})
                q = line[2:].strip()
                a = None
            elif line.startswith("A:"):
                a = line[2:].strip()
            elif a is not None:
                a += " " + line
        if q and a:
            pairs.append({"question": q, "answer": a})
    except Exception:
        pairs = []
    return pairs

