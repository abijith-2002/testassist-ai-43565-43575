@app.post(
    "/answer",
    response_model=ChatAnswer,
    tags=["chat"],
    summary="Get answer to a question (from Gemini only, no fallback)",
    description=(
        "Send any user question. Backend always returns a Gemini-generated answer, "
        "injecting answers.txt as context. If Gemini API config is missing, returns a 400 error."
    ),
    responses={
        400: {"description": "Gemini API misconfiguration or live Gemini error."}
    }
)
async def answer_query(query: ChatQuery):
    """
    All user queries are sent to Google Gemini, with the content of answers.txt included as knowledge context.
    No hardcoded, fallback, or simulated logic is ever used; error is raised for any config issue.
    Ensures that the 'answer' field in the response is NEVER None or empty string, and logs for debugging.
    """
    api_url, api_key = await require_gemini_config()
    answer_text = await query_gemini_live(query.question, api_url, api_key)
    # Defensive logic: guarantee non-empty 'answer' for frontend UX
    if not answer_text or not str(answer_text).strip():
        logger.error(f"Gemini/backing logic produced empty or None answer for question: {repr(query.question)}")
        fallback_message = "[No reply returned by Gemini. Please try again, or check backend logs for errors.]"
        answer_text = fallback_message
    return ChatAnswer(answer=answer_text, from_gemini=True)

# PUBLIC_INTERFACE
@app.post(
    "/chat",
    response_model=ChatAnswer,
    tags=["chat"],
    summary="Chat endpoint (same as /answer, uses Gemini only)",
    description=(
        "Chat interface endpoint. Functions identically to /answer; Gemini answers "
        "every query using answers.txt as context. Returns error if config missing."
    ),
    responses={
        400: {"description": "Gemini API misconfiguration or live Gemini error."}
    }
)
async def chat_interface(query: ChatQuery):
    """
    Identical to /answer. Chat endpoint for conversational UI.

    Ensures 'answer' is NEVER None or empty, with error/debug logging for blank Gemini responses.

    Returns a JSON object: {'answer': <str>, 'from_gemini': True}.

    -- Gemini Extraction & Safeguards --
      - Gemini's reply is extracted as: data['candidates'][0]['content']['parts'][0]['text']
      - If no candidate or text is present, fallback debug/error logging is triggered.
      - Response model guarantees 'answer' is a nonempty string; if empty, a safe fallback is used.

    -- FIELD CONTRACT (Frontend may rely on this) --
      - The reply is returned as:
          {
            "answer": <nonempty string, either Gemini's reply or a fallback>,
            "from_gemini": true
          }
      - This contract is always enforced. The 'answer' key is always present and never empty.
    """
    logger.info(f"Received /chat POST: {repr(query.question)}")
    # Use answer_query to ensure consistent enforcement of non-empty answer
    resp: ChatAnswer = await answer_query(query)
    # Defensive: Further enforce nonempty 'answer', just in case
    answer_text = getattr(resp, "answer", None)
    if not answer_text or not str(answer_text).strip() or answer_text.strip().lower() == "[no reply returned by gemini. please try again, or check backend logs for errors.]":
        logger.error("Final backend answer for /chat was empty or fallback; sending safe fallback string.")
        resp.answer = "Sorry, no answer could be generated at this time. Please try again."
    return resp

