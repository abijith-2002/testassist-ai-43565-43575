@app.get("/", tags=["health"], summary="Health check")
def health_check():
    """
    Simple health check endpoint.
    """
    return {"message": "Healthy"}


# PUBLIC_INTERFACE
@app.post(
    "/answer",
    response_model=ChatAnswer,
    tags=["chat"],
    summary="Retrieve an answer for a user query",
    description=(
        "Given a user's question, always send the query to Gemini, providing the full content of answers.txt in the prompt. "
        "Gemini will use answers.txt as its primary knowledge source if possible, "
        "otherwise fall back to its general knowledge. The backend never returns direct answers; "
        "the response is always generated by Gemini."
    ),
)
async def answer_query(query: ChatQuery):
    """
    Returns Gemini's generated answer to the user's question.
    Always provides the content of answers.txt in the prompt/context to Gemini, instructing it to use this as primary reference.
    Never answers directly from answers.txt.
    """
    gemini_resp = await query_gemini(query.question)
    return ChatAnswer(answer=gemini_resp, from_gemini=True)


from fastapi.responses import JSONResponse
from fastapi import status

# PUBLIC_INTERFACE
@app.post(
    "/chat",
    response_model=ChatAnswer,
    tags=["chat"],
    summary="Chat interface (same as /answer)",
    description="Chat endpoint for conversational Q&A. Always returns Gemini's answer; never from answers.txt."
)
async def chat_interface(query: ChatQuery):
    """
    Conversational endpoint for frontend, always delegates to Gemini with answers.txt as system context.
    Checks that required Gemini API configuration is present and returns a user-facing error if missing.
    """
    missing = []
    gemini_api_url = os.getenv("GEMINI_API_URL")
    gemini_api_key = os.getenv("GEMINI_API_KEY")
    if not gemini_api_url:
        missing.append("GEMINI_API_URL")
    if not gemini_api_key:
        missing.append("GEMINI_API_KEY")
    if missing:
        message = "Required configuration variables missing: " + ", ".join(missing)
        return JSONResponse(
            status_code=status.HTTP_400_BAD_REQUEST,
            content={"error": message, "missing": missing},
        )
    return await answer_query(query)


# PUBLIC_INTERFACE
@app.get("/answers", tags=["chat"], summary="List all available Q&A",
         description="Returns all Q&A pairs from the answers.txt file.")
def list_qa_pairs():
    """
    Returns the full list of Q&A pairs available in answers.txt (for frontend review, cannot post questions here).
    """
    qa_pairs = parse_answers(ANSWERS_FILE)
    return [{"question": q, "answer": a} for q, a in qa_pairs]


